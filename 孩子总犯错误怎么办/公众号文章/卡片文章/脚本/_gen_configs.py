def to_fullwidth(s):
    """把 ASCII 直引号成对替换为中文全角引号"""
    out, open_q = [], True
    for ch in s:
        if ch == '"':
            out.append('\u201c' if open_q else '\u201d')
            open_q = not open_q
        else:
            out.append(ch)
    return ''.join(out)


def walk(o):
    if isinstance(o, str):
        return to_fullwidth(o)
    if isinstance(o, list):
        return [walk(x) for x in o]
    if isinstance(o, dict):
        return {k: walk(v) for k, v in o.items()}
    return o


