BGM_BLOCK = (
"### 背景音乐\n"
"- 曲目：传递的温柔_等电平循环90s.wav\n"
"- 位置：全程\n"
"- 音量：-12\n"
"- 压低：8\n"
"- 斜坡：0.35 秒\n"
)

def find_md(folder):
    fs = glob.glob(os.path.join(BASE, folder, "视频号文案_*.md"))
    fs = [f for f in fs if os.path.isfile(f)]
    return fs[0] if fs else None

results=[]
for num, folder, title, focus, hook, cover in ROWS:
    path = find_md(folder)
    if not path:
        results.append((num, folder, "❌ 找不到 md", None)); continue
    s = open(path, encoding="utf-8").read()
    orig = s
    log=[]

    # 1) 版本 金句 -> 常驻标题
    s2 = re.sub(r"(- \*\*版本\*\*[：:])\s*金句", r"\1 常驻标题", s)
    if s2 != s: log.append("版本→常驻标题")
    s = s2

    # 2) 在「### 开头钩子」整节之后、下一个 ### 之前，插入「### 常驻标题」（若已存在则不重复插）
    if "### 常驻标题" not in s:
        # 找开头钩子节：从 ### 开头钩子 到下一个 ### 或 ##
        m = re.search(r"(### 开头钩子[^\n]*\n)(.*?)(?=^### |^## )", s, re.S|re.M)
        if m:
            block = "\n### 常驻标题\n- 「%s」重点：%s\n- 色：#6E97C9\n\n" % (title, focus)
            s = s[:m.end()] + block + s[m.end():]
            log.append("插入常驻标题节")
        else:
            log.append("⚠️没找到开头钩子节，未插常驻标题")

    # 3) 钩子：替换「钩子节」内第一条 「...」停约 x 秒
    def replace_hook(mm):
        inner = mm.group(0)
        return re.sub(r"「[^」]*」(停约[^。\n]*)?", "「%s」停约 2.5 秒" % hook, inner, count=1)
    s2 = re.sub(r"### 开头钩子[^\n]*\n(.*?)(?=^### |^## )", replace_hook, s, count=1, flags=re.S|re.M)
    if s2 != s: log.append("钩子更新")
    s = s2

    # 4) 封面大字（三、上屏方案 → ### 封面）：替换「- 大字：**...**（备选：...）」
    def replace_cover(mm):
        head = mm.group(0).split("大字")[0]
        return "%s大字：**%s**" % (head, cover)
    s2 = re.sub(r"### 封面[^\n]*\n(.*?)(?=^### |^## |^---)",
                lambda x: re.sub(r"(- )?大字[：:].*", lambda y: ("- 大字：**%s**" % cover), x.group(0), count=1),
                s, count=1, flags=re.S|re.M)
    if s2 != s: log.append("封面大字更新")
    s = s2
    # 兜底：若封面在「五、发布方案」里也有「封面大字：」
    s2 = re.sub(r"(\*\*封面大字\*\*[：:]).*", lambda m: m.group(1)+cover, s)
    if s2 != s: log.append("发布方案封面同步")
    s = s2

    # 5) BGM：在「三、上屏方案」区（## 三 到 ## 四 之间）插入背景音乐块（插在 ### 封面 节之后）
    sec3 = re.search(r"(## 三、上屏方案.*?)(## 四、)", s, re.S)
    if sec3 and "### 背景音乐" not in sec3.group(1):
        block = BGM_BLOCK
        # 优先放在三、上屏方案区末尾（## 四 之前）
        s = s[:sec3.end(1)] + "\n" + block + "\n" + s[sec3.start(2):]
        log.append("上屏区插入BGM块")
    elif sec3 and "### 背景音乐" in sec3.group(1):
        log.append("BGM块已存在")
    else:
        log.append("⚠️未定位三、上屏方案，BGM未插")

    # 6) 四、合成方案 里“不垫/无 BGM”说明改为“已垫”
    s2 = re.sub(r"[^\n]*本条不垫 ?BGM[^\n]*",
                "- **BGM：本条已垫**（系列固定配置：传递的温柔_等电平循环90s.wav／全程／-12／压低8／斜坡0.35，见「三、上屏方案 → 背景音乐」）", s)
    s2 = re.sub(r"[^\n]*不垫 ?BGM[^\n]*",
                "- **BGM：本条已垫**（系列固定配置：传递的温柔_等电平循环90s.wav／全程／-12／压低8／斜坡0.35，见「三、上屏方案 → 背景音乐」）", s2)
    s2 = re.sub(r"[^\n]*全系列无 ?BGM[^\n]*",
                "- **BGM：全系列统一垫**（传递的温柔_等电平循环90s.wav／全程／-12／压低8／斜坡0.35）", s2)
    if s2 != s: log.append("合成区BGM说明改为已垫")
    s = s2

    if WRITE and s != orig:
        open(path,"w",encoding="utf-8").write(s)
    results.append((num, os.path.basename(path), "；".join(log), s!=orig))

for r in results:
    print(r[0], r[1], "->", r[2])
print("\n模式:", "WRITE 落盘" if WRITE else "DRY-RUN（未落盘）")
