def fw(s):
    out, oq = [], True
    for ch in s:
        if ch == '"':
            out.append('\u201c' if oq else '\u201d'); oq = not oq
        else:
            out.append(ch)
    return ''.join(out)


def walk(o):
    if isinstance(o, str): return fw(o)
    if isinstance(o, list): return [walk(x) for x in o]
    if isinstance(o, dict): return {k: walk(v) for k, v in o.items()}
    return o


