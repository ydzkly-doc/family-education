# 匹配：评论区置顶标题 -> 直到 **封面大字** 之间的整块引用
BLOCK = re.compile(r"(\*\*评论区置顶[^\n]*\*\*\n)(.*?)(?=\n\*\*封面大字)", re.S)

def find_file(num):
    hits = glob.glob(os.path.join(BASE, num + "_*", "*.md"))
    hits = [h for h in hits if os.path.basename(h).startswith("视频号文案_")]
    assert len(hits) == 1, (num, hits)
    return hits[0]

def main():
    apply = "--apply" in sys.argv
    assert set(LINES) == {("%02d" % i) for i in range(34)}, "LINES 必须覆盖 00-33"
    ok = 0
    for i in range(34):
        num = "%02d" % i
        path = find_file(num)
        src = open(path, encoding="utf-8").read()
        m = BLOCK.search(src)
        assert m, (num, "未找到置顶块")
        new_body = "\n".join("> " + s for s in LINES[num])
        new_block = m.group(1) + new_body
        n_old_lead = src.count("公众号那个系列里了")
        out = src[:m.start()] + new_block + src[m.end():]
        if apply:
            with open(path, "w", encoding="utf-8") as f:
                f.write(out)
        ok += 1
        print("%s  %-58s 旧引流句x%d -> %d 行" % (num, os.path.basename(os.path.dirname(path)), n_old_lead, len(LINES[num])))
    print(("已写盘 " if apply else "dry-run ") + str(ok) + "/34")

main()
