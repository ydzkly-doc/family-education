# -*- coding: utf-8 -*-
"""07 条的 19 字句不硬塞：从「强调句」移到「浅底卡」（与 04 的照念台词同一处置）。

理由（SOP 3.18① ＋ hk55）：
    「这是我处理错了，不能怪你当时没解释好。」19 字，82px（cap 10）会折 **2 行且把词劈开**
    （实测断成"这是我处理错了，不／能怪你当时没解释好。"）→ 只改了它就没法满足 hk55 判据。
    → 正解：**走浅底卡**（76px、cap 11、允许 3 行），它本来就适合"一句完整、可以截图的话"。
    ⛔ 不要靠硬压字数解决——那是把观众要读的句子砍短。
"""
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
BASE = r"D:\个人资料\家庭教育\公众号\改善你的亲子关系\视频号文案"
F07 = "07_道歉最难的不是对不起/视频号文案_07_发布第7条_第4篇_道歉最难的不是对不起.md"

R = [
("07 强调句·移出19字句", F07,
 """4. 「道歉不是为了被原谅，是让下次不一样。」 → "让下次不一样"标暖色加粗
5. 「这是我处理错了，不能怪你当时没解释好。」 → "不能怪你"标暖色加粗""",
 """4. 「道歉不是为了被原谅，是让下次不一样。」 → "让下次不一样"标暖色加粗"""),

("07 浅底卡·说明为什么走浅底卡", F07,
 """### 浅底卡（画面下方浅底文字卡）
1. 「这是我处理错了，不能怪你当时没解释好」→ 挂在「这是我处理错了，不能怪你当时没解释好。」""",
 """### 浅底卡（画面下方浅底文字卡）
1. 「这是我处理错了，不能怪你当时没解释好」→ **停 4 秒**（19 字，82px 会折成两行并把词劈开，所以走 76px 的浅底卡）；挂在「这是我处理错了，不能怪你当时没解释好。」"""),

("07 录制提示·同步", F07,
 """- 底部字幕（5 句）：「难的不是说出对不起，是不替自己辩护。」「可它们会悄悄把道歉，变成另一场申辩。」「孩子最后收到的，还是那半句但是。」「道歉不是为了被原谅，是让下次不一样。」「这是我处理错了，不能怪你当时没解释好。」""",
 """- 底部字幕（4 句）：「难的不是说出对不起，是不替自己辩护。」「可它们会悄悄把道歉，变成另一场申辩。」「孩子最后收到的，还是那半句但是。」「道歉不是为了被原谅，是让下次不一样。」"""),

("07 浅底卡挂句·并入", F07,
 """- 浅底卡挂句（1 句）：「这是我处理错了，不能怪你当时没解释好。」
""",
 """- 浅底卡挂句（1 句）：「这是我处理错了，不能怪你当时没解释好。」（**这句走浅底卡、不上底部字幕**——19 字在 82px 下会折两行且劈词）
"""),
]

bad = 0
for label, rel, old, new in R:
    p = os.path.join(BASE, rel)
    t = io.open(p, encoding="utf-8").read()
    n = t.count(old)
    if n == 0:
        print(f"❌ {label}：0 处")
        bad += 1
        continue
    io.open(p, "w", encoding="utf-8").write(t.replace(old, new))
    print(f"✅ {label}：{n} 处")

print()
print("全部通过 ✅" if not bad else f"⚠️ {bad} 处需人工看")
sys.exit(1 if bad else 0)
