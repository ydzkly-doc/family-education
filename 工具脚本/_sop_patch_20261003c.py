def norm(s: str) -> str:
    """把中文引号归一成 ASCII 双引号（1:1 字符替换，下标可直接复用）。"""
    return (s.replace("\u201c", '"').replace("\u201d", '"')
             .replace("\u2018", "'").replace("\u2019", "'"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="只报告命中，不写入")
    ap.add_argument("--file", default=SOP, help="目标 SOP 路径（默认专家包缓存副本）")
    a = ap.parse_args()

    path = a.file
    t = io.open(path, encoding="utf-8").read()
    nt = norm(t)
    print(f"目标：{path}\n原始 {len(t)} 字符\n")

    problems, applied = [], 0
    for label, old, new, exp in R:
        protect_hit = [k for k in PROTECT if k in old]
        if protect_hit:
            problems.append(f"⛔ {label}：原文含保护词 {protect_hit} —— 拒绝执行（这些规则本次一律不动）")
            continue
        n = nt.count(norm(old))
        if n != exp:
            problems.append(f"❌ {label}：命中 {n} 处（预期 {exp}）")
            continue
        if a.dry_run:
            print(f"✅ {label}：命中 {n} 处")
            continue
        i = nt.find(norm(old))
        t = t[:i] + new + t[i + len(old):]
        nt = norm(t)
        applied += 1
        print(f"✅ {label}：已替换")

    if not a.dry_run:
        io.open(path, "w", encoding="utf-8").write(t)
        print(f"\n已写入 {path}（{applied} 处）")

    if problems:
        print("\n=== 需要处理 ===")
        for p in problems:
            print("  " + p)
        return 1
    print("\n全部通过 ✅")
    return 0


if __name__ == "__main__":
    sys.exit(main())
