def norm(s: str) -> str:
    """把中文引号归一成 ASCII 双引号（1:1 字符替换，下标可直接复用）。"""
    return (s.replace("\u201c", '"').replace("\u201d", '"')
             .replace("\u2018", "'").replace("\u2019", "'"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="只报告命中，不写入")
    ap.add_argument("--file", default=SOP, help="目标 SOP 路径（默认专家包缓存副本）")
    a = ap.parse_args()

    path = a.file
    t = io.open(path, encoding="utf-8").read()
    nt = norm(t)
    print(f"目标：{path}\n原始 {len(t)} 字符\n")

    problems, applied = [], 0
    for label, old, new, exp in R:
        protect_hit = [k for k in PROTECT if k in old]
        if protect_hit:
            problems.append(f"⛔ {label}：原文含保护词 {protect_hit} —— 拒绝执行（这些规则本次一律不动）")
            continue
        n = nt.count(norm(old))
        if n != exp:
            problems.append(f"❌ {label}：命中 {n} 处（预期 {exp}）")
            continue
        if a.dry_run:
            print(f"✅ {label}：命中 {n} 处")
            continue
        # 从后往前替换，避免下标漂移
        idx = 0
        while True:
            i = nt.find(norm(old), idx)
            if i < 0:
                break
            t = t[:i] + new + t[i + len(old):]
            nt = norm(t)
            idx = i + len(new)
        applied += 1
        print(f"✅ {label}：已替换")

    if not a.dry_run:
        print()
        for o, nw in GLOBAL:
            pairs = [(o, nw)]
            if norm(o) != o:
                pairs.append((norm(o), norm(nw)))
            for a_, b_ in pairs:
                c = t.count(a_)
                if c:
                    t = t.replace(a_, b_)
                    print(f"✅ 编号改名 {a_} → {b_}：{c} 处")
        io.open(path, "w", encoding="utf-8").write(t)
        print(f"\n已写入 {path}")

    if problems:
        print("\n=== 需要处理 ===")
        for p in problems:
            print("  " + p)
        return 1
    print("\n全部通过 ✅")
    return 0


