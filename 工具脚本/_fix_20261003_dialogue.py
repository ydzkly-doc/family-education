def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    bad = 0
    for label, rel, old, new in R:
        p = os.path.join(BASE, rel)
        t = io.open(p, encoding="utf-8").read()
        n = t.count(old)
        if n == 0:
            print(f"❌ {label}：0 处命中")
            bad += 1
            continue
        if a.dry_run:
            print(f"✅ {label}：命中 {n} 处")
            continue
        # ⚠️ 全量替换：同一句在「口播区／提词器区」各出现一次（提词器会被 gen_prompter 整体覆盖）
