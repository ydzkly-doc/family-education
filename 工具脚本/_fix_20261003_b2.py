# -*- coding: utf-8 -*-
"""修正 06/07 首轮自检抓出的问题 ＋ 回填抬头块实测时长。"""
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
BASE = r"D:\个人资料\家庭教育\公众号\改善你的亲子关系\视频号文案"
F06 = "06_一日语言审计四个问题/视频号文案_06_发布第6条_第3篇_一日语言审计四个问题.md"
F07 = "07_道歉最难的不是对不起/视频号文案_07_发布第7条_第4篇_道歉最难的不是对不起.md"

R = [
# 分句 > 16 字：`？` 不是分句切分符（只认 ，、；：），所以"？"后面那句会被算进同一个分句
("06 分句超长", F06,
 "那怎么改呢？我后来把要求换成四个部分。",
 "那怎么改呢？我后来把要求，换成四个部分。"),

("07 分句超长", F07,
 "这些话也许都能解释我当时为什么失控。",
 "这些话也许能解释，我当时为什么失控。"),

# 抬头块回填实测
("06 抬头块", F06,
 "**时长 ≈130 秒级／形态：方法型",
 "**时长 ≈134 秒（2:14）／口播 577 字含标点；真片预计 141~144 秒（2.4 分）｜ 形态：方法型"),

("07 抬头块", F07,
 "**形态：情绪型（一件具体的事",
 "**时长 ≈124 秒（2:04）／口播 532 字含标点；真片预计 130~132 秒（2.2 分）｜ 形态：情绪型（一件具体的事"),
]

bad = 0
for label, rel, old, new in R:
    p = os.path.join(BASE, rel)
    t = io.open(p, encoding="utf-8").read()
    n = t.count(old)
    if n == 0:
        print(f"❌ {label}：0 处")
        bad += 1
        continue
    io.open(p, "w", encoding="utf-8").write(t.replace(old, new))
    print(f"✅ {label}：{n} 处")

print()
print("全部通过 ✅" if not bad else f"⚠️ {bad} 处需人工看")
sys.exit(1 if bad else 0)
