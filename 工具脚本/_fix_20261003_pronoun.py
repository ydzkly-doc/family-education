'''通顺性修正 第五轮：**与 SOP 3.9 对齐**（用户提醒"原有规则别冲突"）。

SOP 3.9 铁律：指代家人写「称呼」不写「代词」（指孩子 → 写「孩子」）；
            自检清单 1610 给它留了口子：**"他"只在必要处（宾语／条件从句／引语／金句）**。
→ 本轮我改稿时新引入的 4 处「他作叙述主语」，与 3.9 冲突，改回「孩子」或改用语序；
  作宾语／定语的照留。
'''
import argparse
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

BASE = r"D:\个人资料\家庭教育\公众号\改善你的亲子关系\视频号文案"
F03 = "03_每句话都对为什么一说就错/视频号文案_03_发布第3条_第2篇_每句话都对为什么一说就错.md"
F04 = "04_孩子递过来的是三件事/视频号文案_04_发布第4条_第2篇_孩子递过来的是三件事.md"
F05 = "05_对同事客客气气回家只剩命令/视频号文案_05_发布第5条_第3篇_对同事客客气气回家只剩命令.md"
F07 = "07_道歉最难的不是对不起/视频号文案_07_发布第7条_第4篇_道歉最难的不是对不起.md"

R = [
    # 03：段二"孩子"密度要控住（3.9 说 4 次以上就绕）→ 一处改称呼、一处改语序
    ("03 视角句·他→孩子", F03,
     '''在他听来，只剩一句话。''',
     '''在孩子听来，只剩一句话。'''),

    ("03 心声里的「他」→「孩子」", F03,
     '''我回来，不是为了他经历了什么，而是为了证明我当初说对了。''',
     '''我回来，不是为了孩子经历了什么，而是为了证明我当初说对了。'''),

    ("03 主语代称改语序（防「孩子」堆叠）", F03,
     '''孩子会觉得自己，只能站在错的那一边。
接下来他哪还有心思复盘，只想护住剩下那点体面。''',
     '''这么一来，只会剩下错的那一边可站。
接下来哪还有心思复盘，只想护住剩下那点体面。'''),

    # 04：主语位 → 称呼；宾语位的「他」照留
    ("04 引语引导语·他→孩子", F04,
     '''他听到的是，我关心的只是问题赶紧消失，不是他刚刚经历了什么。''',
     '''孩子听到的是，我关心的只是问题赶紧消失，不是他刚刚经历了什么。'''),

    # 05：两句都改（孩子视角 → 家长自述），保对照、不堆叠
    ("05 换位句·他刚进门", F05,
     '''他刚进门，我先看见地上的书包。''',
     '''进门那一刻，我先看见地上的书包。'''),

    ("05 换位句·孩子想说", F05,
     '''他想说今天的事，我已经列了四件。''',
     '''孩子想说今天的事，我已经列了四件。'''),

    # 07：定语位用称呼；小句主语改称呼
    ("07 定语·他的受伤→孩子的受伤", F07,
     '''他的受伤，得先理解我的不容易。''',
     '''孩子的受伤，得先理解我的不容易。'''),

    ("07 小句主语·他→孩子", F07,
     '''要看他在我说完之后，会不会真的先问一句。''',
     '''要看孩子在我说完之后，会不会真的先问一句。'''),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    files = {}
    warn = 0
    for label, rel, old, new in R:
        p = os.path.join(BASE, rel)
        if p not in files:
            files[p] = io.open(p, encoding="utf-8").read()
        n = files[p].count(old)
        if n < 1:
            warn += 1
        print(f"{'✅' if n else '❌'} [{label}] 命中 {n} 处")
        if n and not a.dry_run:
            files[p] = files[p].replace(old, new)

    if not a.dry_run:
        for p, t in files.items():
            io.open(p, "w", encoding="utf-8").write(t)
    print(f"\n未命中 {warn} 处" + ("（--dry-run，未写入）" if a.dry_run else ""))
    return 1 if warn else 0


if __name__ == "__main__":
    sys.exit(main())
