def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    files = {}          # path -> text
    warn = 0
    for label, rel, old, new in R:
        p = os.path.join(BASE, rel)
        if p not in files:
            files[p] = io.open(p, encoding="utf-8").read()
        n = files[p].count(old)
        flag = "✅" if n >= 1 else "❌"
        if n < 1:
            warn += 1
        print(f"{flag} [{label}] 命中 {n} 处")
        if n >= 1 and not a.dry_run:
            files[p] = files[p].replace(old, new)

    if not a.dry_run:
        for p, t in files.items():
            io.open(p, "w", encoding="utf-8").write(t)
        print(f"\n已写入 {len(files)} 个文件")
    print(f"\n未命中 {warn} 处" + ("（--dry-run，未写入）" if a.dry_run else ""))
    return 1 if warn else 0


if __name__ == "__main__":
    sys.exit(main())
