def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    bad = 0
    for label, rel, start, end, body in R:
        p = os.path.join(BASE, rel)
        t = io.open(p, encoding="utf-8").read()
        try:
            i = t.index(start)
            j = t.index(end, i + len(start))
        except ValueError:
            print(f"❌ [{label}] 找不到区块边界")
            bad += 1
            continue
        old_len = j - i
        print(f"✅ [{label}] 旧 {old_len} 字符 → 新 {len(body)} 字符")
        if not a.dry_run:
            io.open(p, "w", encoding="utf-8").write(t[:i] + body + t[j:])

    for label, rel, old, new in PATCH:
        if old == new:
            continue
        p = os.path.join(BASE, rel)
        t = io.open(p, encoding="utf-8").read()
        n = t.count(old)
        if n != 1:
            print(f"⚠️ [{label}] 命中 {n} 处（跳过）")
            continue
        print(f"✅ [{label}] 定点补丁")
        if not a.dry_run:
            io.open(p, "w", encoding="utf-8").write(t.replace(old, new, 1))

    print(f"\n异常 {bad} 处" + ("（--dry-run，未写入）" if a.dry_run else ""))
