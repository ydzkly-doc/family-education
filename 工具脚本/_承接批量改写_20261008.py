def find_file(num):
    ds = glob.glob(os.path.join(BASE, num + "_*"))
    ds = [d for d in ds if os.path.isdir(d)]
    if len(ds) != 1:
        return None
    fs = glob.glob(os.path.join(ds[0], "视频号文案_*.md"))
    return fs[0] if len(fs) == 1 else None

def must_replace(t, old, new, tag):
    if t.count(old) != 1:
        raise SystemExit("❌[%s] 命中 %d 次（应为1）：\n%s" % (tag, t.count(old), old[:60]))
    return t.replace(old, new)

def process(num, apply):
    f = find_file(num)
    if not f:
        raise SystemExit("❌ 找不到 %s 的唯一 md" % num)
    t = io.open(f, encoding="utf-8").read()
    log = []

    # ── 开场：标记 + 旧编号句 ──
    if num in OPEN:
        m = re.search(r"【开场·接上一条】\n\n(上一条我说[^。\n]*。)", t)
        if not m:
            raise SystemExit("❌[%s] 开场旧句未匹配" % num)
        old_open = m.group(1)
        t = t.replace("【开场·接上一条】\n\n" + old_open,
                      "【开场·承接】\n\n" + OPEN[num], 1)
        log.append("开场：%s → %s" % (old_open[:18], OPEN[num][:18]))
        # 08：口播区第二句“这句话”指代微调（系列方案里的同名句由后面整块重写）
        if num == "08":
            t = must_replace(t, OPEN["08"] + "\n这句话听久了，很容易听出一句责备。",
                                OPEN["08"] + "\n这话听久了，很容易听出一句责备。", "08指代")

    # ── 收尾：标记 + 旧编号句 ──
    if num in CLOSE:
        m = re.search(r"【合集·过渡】\n\n(下一条我说[^。\n]*。)", t)
        if not m:
            raise SystemExit("❌[%s] 收尾旧句未匹配" % num)
        old_close = m.group(1)
        t = t.replace("【合集·过渡】\n\n" + old_close,
                      "【落点·收尾】\n\n" + CLOSE[num], 1)
        log.append("收尾：%s → %s" % (old_close[:18], CLOSE[num][:18]))

    # ── 提词器区里的“上一条我说，// …”“下一条我说，// …”残留 ──
    # 这些在重生提词器时会自动清，但先标记，避免漏。
    # ── 发布方案·评论区置顶末行：替换编号句为系列坐标 ──
    t = re.sub(r"\n> 下一条我说[：:][^\n]*。(?=\n)",
               "\n> 《孩子与手机》这一系列，我一条一条往下说。", t)

    # ── 朋友圈②段：去掉“上一条我说了…”，统一成话题承接 ──
    t = re.sub(r"> 上一条我说了[^\n]*?，再往下(?:看一层|想一层|说|往下说)：",
               "> 说完上一层，再往下看：", t)

    if apply:
        io.open(f, "w", encoding="utf-8").write(t)
    print("✅ %s  %s" % (num, "；".join(log)))
    return f

if __name__ == "__main__":
    apply = "--apply" in sys.argv
