def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    bad = 0
    for label, rel, old, new in R:
        p = os.path.join(BASE, rel)
        t = io.open(p, encoding="utf-8").read()
        n = t.count(old)
        if n == 0:
            print(f"❌ {label}：0 处命中")
            bad += 1
            continue
        if a.dry_run:
            print(f"✅ {label}：命中 {n} 处")
            continue
        # ⚠️ **全量替换**：同一句本来就会在「口播／上屏方案／录制提示／提词器」四处各出现一次，
        #    只改一处会造成"改了 A 忘了 B" —— 那正是 SOP 反复踩的坑（改完不重数上屏清单）。
        #    提词器那几处会在下一次 `gen_prompter` 时被整体覆盖，不影响。
        t = t.replace(old, new)
        io.open(p, "w", encoding="utf-8").write(t)
        print(f"✅ {label}：已替换 {n} 处")

    print()
    if bad:
        print(f"⚠️ {bad} 处需人工看一眼")
        return 1
    print("全部通过 ✅" + ("（--dry-run，未写入）" if a.dry_run else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
