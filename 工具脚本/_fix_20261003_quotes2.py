# -*- coding: utf-8 -*-
'''通顺性修正 第三轮：引号层面的实际错误。
  ① 09 备选开头结尾把「」写成了 "（不成对）；
  ② 备选开头里的引语用 ASCII 单引号 '，与其他引语的双引号不一致（这几句是要念的）；
  ③ 11 的浅底卡条目里，同一句上屏文案用了中文引号、挂句用了 ASCII，两边看着不像同一句。
'''
import argparse
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

BASE = r"D:\个人资料\家庭教育\公众号\改善你的亲子关系\视频号文案"
F03 = "03_每句话都对为什么一说就错/视频号文案_03_发布第3条_第2篇_每句话都对为什么一说就错.md"
F07 = "07_道歉最难的不是对不起/视频号文案_07_发布第7条_第4篇_道歉最难的不是对不起.md"
F08 = "08_旧账说清楚四个动作/视频号文案_08_发布第8条_第4篇_旧账说清楚四个动作.md"
F09 = "09_先修关系会不会把孩子惯坏/视频号文案_09_发布第9条_第5篇_先修关系会不会把孩子惯坏.md"
F10 = "10_关系缓和后规则怎么写才能执行/视频号文案_10_发布第10条_第5篇_关系缓和后规则怎么写才能执行.md"
F11 = "11_情感账户不是交易/视频号文案_11_发布第11条_第2篇_情感账户不是交易.md"

R = [
    ("09 备选开头·「」写成 \"", F09,
     '''「那是我最担心的一件事：先听他说，是不是就等于迟到没事。"''',
     '''「那是我最担心的一件事：先听他说，是不是就等于迟到没事。」'''),

    ("03 备选开头·单引号→双引号", F03,
     ''''别拖到最后一天，要提前检查。我知道。' ''',
     '''"别拖到最后一天，要提前检查。我知道。"'''),

    ("07 备选开头·单引号→双引号", F07,
     '''那次是'爸爸说重了，但还不是因为担心你'。」''',
     '''那次是"爸爸说重了，但还不是因为担心你"。」'''),

    ("08 备选开头·单引号→双引号", F08,
     '''「他没说'没关系'，只回了一句'以后先问我'。」''',
     '''「他没说"没关系"，只回了一句"以后先问我"。」'''),

    ("10 备选开头·单引号→双引号", F10,
     '''「我把'九点半到家'这条规则，前后改过好几遍。」''',
     '''「我把"九点半到家"这条规则，前后改过好几遍。」'''),

    ("11 备选开头·单引号→双引号", F11,
     '''「我一直觉得，'对孩子好'这件事，很容易被当成一笔人情账。」''',
     '''「我一直觉得，"对孩子好"这件事，很容易被当成一笔人情账。」'''),

    ("11 浅底卡·同一句内两种引号", F11,
     '''1. 「他说“别告诉别人”，就别变成谈资」''',
     '''1. 「他说"别告诉别人"，就别变成谈资」'''),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    files = {}
    warn = 0
    for label, rel, old, new in R:
        p = os.path.join(BASE, rel)
        if p not in files:
            files[p] = io.open(p, encoding="utf-8").read()
        n = files[p].count(old)
        if n < 1:
            warn += 1
        print(f"{'✅' if n else '❌'} [{label}] 命中 {n} 处")
        if n and not a.dry_run:
            files[p] = files[p].replace(old, new)

    if not a.dry_run:
        for p, t in files.items():
            io.open(p, "w", encoding="utf-8").write(t)
    print(f"\n未命中 {warn} 处" + ("（--dry-run，未写入）" if a.dry_run else ""))
    return 1 if warn else 0


if __name__ == "__main__":
    sys.exit(main())
