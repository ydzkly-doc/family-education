def h2(text):
    return (f'<section style="margin:34px 0 16px;"><table cellpadding="0" cellspacing="0" border="0" style="width:100%;">'
            f'<tr><td style="width:6px;background:{C_MAIN};border-radius:3px;"></td>'
            f'<td style="padding-left:12px;font-size:20px;font-weight:bold;color:{C_DARK};line-height:1.5;">{text}</td>'
            f'</tr></table></section>')

def p(text):
    return f'<p style="margin:16px 0;font-size:16px;line-height:1.9;color:{C_DARK};letter-spacing:0.3px;">{text}</p>'

def quote(text):
    # 金句块：用 <br> 在语义停顿处手动均衡断行（手机端每行约 13~16 字），
    # 加 word-break:keep-all + 宽松左右 padding，避免窄屏出现"一字成行"的孤字。
    return (f'<section style="margin:26px 0;text-align:center;">'
            f'<table cellpadding="0" cellspacing="0" border="0" align="center" style="width:92%;">'
            f'<tr><td style="background:{C_BG};border-radius:10px;padding:20px 22px;'
            f'font-size:17px;font-weight:bold;color:{C_MAIN};line-height:1.9;text-align:center;'
            f'word-break:keep-all;overflow-wrap:break-word;letter-spacing:0.5px;">{text}</td>'
            f'</tr></table></section>')

def three(items):
    rows = ""
    for i, it in enumerate(items, 1):
        rows += (f'<tr><td style="padding:12px 14px;font-size:15.5px;color:{C_DARK};line-height:1.8;">'
                 f'<span style="display:inline-block;background:{C_MAIN};color:#fff;font-weight:bold;'
                 f'width:22px;height:22px;line-height:22px;text-align:center;border-radius:50%;'
                 f'margin-right:8px;font-size:14px;">{i}</span>{it}</td></tr>')
    return (f'<section style="margin:24px 0;"><table cellpadding="0" cellspacing="0" border="0" style="width:100%;'
            f'background:{C_BG};border-radius:12px;overflow:hidden;">'
            f'<tr><td style="background:{C_MAIN};color:#fff;font-size:16px;font-weight:bold;padding:12px 18px;">'
            f'🌙 今晚就能做的 3 件事</td></tr>{rows}</table></section>')

def card(path_in_cards, caption=""):
    # 读取卡片 HTML，抽取 body 内最外层 table
    with open(os.path.join(BASE, "卡片", path_in_cards), encoding="utf-8") as f:
        html = f.read()
    start = html.find("<table")
    end = html.rfind("</table>") + len("</table>")
    table = html[start:end]
    cap = f'<p style="text-align:center;font-size:13px;color:#9a8f83;margin:6px 0 0;">{caption}</p>' if caption else ""
    return f'<section style="margin:28px 0;">{table}{cap}</section>'

def footer():
    return (f'<section style="margin:36px 0 12px;text-align:center;">'
            f'<table cellpadding="0" cellspacing="0" border="0" align="center" style="width:92%;">'
            f'<tr><td style="background:{C_MAIN};border-radius:12px;padding:20px;color:#fff;">'
            f'<div style="font-size:17px;font-weight:bold;margin-bottom:8px;">📍 {SIGN}</div>'
            f'<div style="font-size:14px;line-height:1.9;color:#ffe9d9;">陪你和孩子，一步步走出低谷。<br>'
            f'愿这些文字，也能到一个正需要它的家庭那里。</div>'
            f'</td></tr></table></section>'
            f'<section style="margin:20px 0;border-top:1px dashed #d8c9bb;padding-top:14px;">'
            f'<p style="font-size:12.5px;color:#9a8f83;line-height:1.8;">来源声明：{DECL}</p></section>')

def article(no, title, sub, blocks, next_hint):
    body = ""
    body += (f'<section style="text-align:center;margin:10px 0 6px;">'
             f'<span style="display:inline-block;background:{C_LIGHT};color:{C_SUB};font-size:13px;'
             f'padding:4px 14px;border-radius:20px;">家庭教育 · 厌学重启系列 第{no}篇</span></section>')
    body += f'<h1 style="font-size:24px;font-weight:bold;color:{C_DARK};line-height:1.5;text-align:center;margin:14px 0 6px;">{title}</h1>'
    if sub:
        body += f'<p style="text-align:center;font-size:14px;color:#9a8f83;margin:0 0 10px;">{sub}</p>'
    body += f'<section style="border-top:2px solid {C_MAIN};width:60px;margin:14px auto;"></section>'
    for b in blocks:
        body += b
    if next_hint:
        body += quote(next_hint)
    body += footer()
    page = (f'<!DOCTYPE html><html lang="zh-CN"><head><meta charset="UTF-8">'
            f'<meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>{title}</title></head><body style="margin:0;padding:0;background:#ffffff;'
            f'font-family:\'Microsoft YaHei\',\'微软雅黑\',sans-serif;">'
            f'<section style="max-width:677px;margin:0 auto;padding:24px 18px;background:#ffffff;">{body}</section>'
            f'</body></html>')
    fn = os.path.join(OUT, f"第{no}篇_{title[:12]}.html")
    with open(fn, "w", encoding="utf-8") as f:
        f.write(page)
    print("written:", fn)

