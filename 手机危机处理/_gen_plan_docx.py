BROWN=(0xb0,0x6a,0x48); DARK=(0x8a,0x4f,0x33); BODY=(0x3a,0x32,0x2c)
GRAY=(0x6b,0x5d,0x52); QCOL=(0x93,0x55,0x3a)

def sf(run,size=10.5,bold=False,color=BODY):
    run.font.name='微软雅黑'; run._element.rPr.rFonts.set(qn('w:eastAsia'),'微软雅黑')
    run.font.size=Pt(size); run.font.bold=bold
    if color: run.font.color.rgb=RGBColor(*color)

def h1(t):
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(12); p.paragraph_format.space_after=Pt(4)
    sf(p.add_run(t),14,True,BROWN)

def h2(t):
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(8); p.paragraph_format.space_after=Pt(2)
    sf(p.add_run(t),11.5,True,DARK)

def para(t,size=10.5,bold=False,color=BODY,after=4):
    p=doc.add_paragraph(); p.paragraph_format.space_after=Pt(after); sf(p.add_run(t),size,bold,color)

def quote(t):
    for line in t.split("\n"):
        p=doc.add_paragraph(); p.paragraph_format.left_indent=Cm(0.6); p.paragraph_format.space_after=Pt(2)
        sf(p.add_run(line),10.5,False,QCOL)

def bullet(t,bold=False):
    p=doc.add_paragraph(); p.paragraph_format.left_indent=Cm(0.5); p.paragraph_format.space_after=Pt(2)
    sf(p.add_run("· "+t),10.5,bold)

def numbered(n,t):
    p=doc.add_paragraph(); p.paragraph_format.left_indent=Cm(0.3); p.paragraph_format.space_after=Pt(2)
    sf(p.add_run(f"{n}. {t}"),10.5)

